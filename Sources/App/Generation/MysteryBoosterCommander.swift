//
//  MysteryBoosterCommander.swift
//  TabletopSimulatorMagicBoosterPackServer
//
//  Support for generating Mystery Booster: Commander Edition (set code MBC) packs.
//
//  Scryfall does not track the new-to-Magic Commander Edition cards accurately, so the
//  contents of each slot are described here as internal lists of card identifiers rather
//  than being derived from a single Scryfall set. The reprint slots reference cards by
//  name + set code, while the MBC-native cards (new commanders, acorn Alchemy cards, and
//  the Future Sight frame cards printed in MBC) are referenced by collector number in the
//  `mbc` set.
//
//  Each booster contains 20 cards:
//    - 3 White common or uncommon reprints
//    - 3 Blue common or uncommon reprints
//    - 3 Black common or uncommon reprints
//    - 3 Red common or uncommon reprints
//    - 3 Green common or uncommon reprints
//    - 1 Reprint wildcard of any rarity
//    - 1 Rare or mythic reprinted commander
//    - 1 New-to-Magic commander (non-foil 95.25% / traditional foil 4.75%)
//    - 1 Future Sight frame card OR acorn card:
//        - Non-foil (43.3%) or foil (2%) common/uncommon Future Sight frame card
//        - Non-foil (52%) or foil (2.4%) rare/mythic Future Sight frame card
//        - Traditional foil acorn stamp card (< 1%)
//    - 1 Playtest card
//

import Foundation

// MARK: - Identifier helpers

/// Builds `.collectorNumberSet` identifiers for cards in the `mbc` set.
private func mbcCards(_ pairs: [(Int, String)]) -> [MTGCardIdentifier] {
	pairs.map { .collectorNumberSet(collectorNumber: "\($0.0)", set: "mbc", name: $0.1) }
}

/// Builds `.collectorNumberSet` identifiers for playtest cards in the `mb2` set.
private func mb2Cards(_ pairs: [(Int, String)]) -> [MTGCardIdentifier] {
	pairs.map { .collectorNumberSet(collectorNumber: "\($0.0)", set: "mb2", name: $0.1) }
}

/// A reprint-slot card. On The List (`plst`) it is reprinted under a collector number of the
/// form `ORIGINALSET-NUMBER` (e.g. Noose Constrictor from EMN #164 is `plst` #`EMN-164`), which
/// is preferred; the original printing is kept as a fallback for when Scryfall doesn't yet have
/// the List printing.
struct ReprintCard {
	let plst: MTGCardIdentifier
	let original: MTGCardIdentifier
}

/// Builds `ReprintCard`s from (original set code, collector number, name) triples. The List
/// collector numbers were resolved from Scryfall ahead of time and hardcoded in the lists below.
private func reprintCards(_ triples: [(String, String, String)]) -> [ReprintCard] {
	triples.map { (set, number, name) in
		ReprintCard(
			plst: .collectorNumberSet(collectorNumber: "\(set.uppercased())-\(number)", set: "plst", name: name),
			original: .collectorNumberSet(collectorNumber: number, set: set.lowercased(), name: name)
		)
	}
}

/// Builds `.collectorNumberSet` identifiers from (set code, collector number, name) triples.
/// Used for the Future Sight frame cards, which span both the `mb2` and `mbc` sets.
private func futureSightCards(_ triples: [(String, Int, String)]) -> [MTGCardIdentifier] {
	triples.map { .collectorNumberSet(collectorNumber: "\($0.1)", set: $0.0.lowercased(), name: $0.2) }
}

