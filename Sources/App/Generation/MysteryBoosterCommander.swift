// MARK: - Fetching & processing

/// A single planned card. `primary` is fetched first; if Scryfall doesn't have it, `fallback`
/// (when present) is used instead. For the reprint slots the primary is the The List (`plst`)
/// printing and the fallback is the original printing.
private struct PlannedCard {
	let primary: MTGCardIdentifier
	let fallback: MTGCardIdentifier?
	let isFoil: Bool

	init(_ primary: MTGCardIdentifier, fallback: MTGCardIdentifier? = nil, isFoil: Bool = false) {
		self.primary = primary
		self.fallback = fallback
		self.isFoil = isFoil
	}

	init(_ reprint: ReprintCard, isFoil: Bool = false) {
		self.primary = reprint.plst
		self.fallback = reprint.original
		self.isFoil = isFoil
	}
}

/// Fetches the given identifiers from Scryfall in chunks and maps them to `MTGCard`s.
private func fetchCards(_ identifiers: [MTGCardIdentifier]) async -> [MTGCard] {
	let collections: [Swiftfall.CardCollectionList] = await identifiers.chunked(by: 75).asyncCompactMap { chunk in
		try? await Swiftfall.getCollection(identifiers: chunk)
	}
	return Array(collections.map(\.data).joined()).map(MTGCard.init)
}

/// Plans a single pack by choosing the card (and foil status) for each slot.
private func planMysteryBoosterCommanderPack() -> [PlannedCard] {
	var planned: [PlannedCard] = []

	// 3 common/uncommon reprints of each color (from The List).
	for reprints in [whiteReprints, blueReprints, blackReprints, redReprints, greenReprints] {
		for reprint in reprints.choose(3) {
			planned.append(PlannedCard(reprint))
		}
	}

	// 1 reprint wildcard of any rarity (from The List).
	if let wildcard = wildcardReprints.randomElement() {
		planned.append(PlannedCard(wildcard))
	}

	// 1 rare or mythic reprinted commander (from The List).
	if let commander = reprintedCommanderReprints.randomElement() {
		planned.append(PlannedCard(commander))
	}

	// 1 new-to-Magic commander: non-foil 95.25% / traditional foil 4.75%.
	if let newCommander = newCommanderIdentifiers.randomElement() {
		let isFoil = (1...10000).randomElement()! <= 475
		planned.append(PlannedCard(newCommander, isFoil: isFoil))
	}

	// 1 Future Sight frame card or acorn stamp card, weighted by rarity and finish.
	//   1...433    (43.3%) non-foil common/uncommon Future Sight frame
	//   434...453   (2.0%) foil common/uncommon Future Sight frame
	//   454...973  (52.0%) non-foil rare/mythic Future Sight frame
	//   974...997   (2.4%) foil rare/mythic Future Sight frame
	//   998...1000  (0.3%) foil acorn stamp card
	let futureSightRoll = (1...1000).randomElement()!
	switch futureSightRoll {
	case 1...433:
		if let card = futureSightCommonUncommonIdentifiers.randomElement() {
			planned.append(PlannedCard(card))
		}
	case 434...453:
		if let card = futureSightCommonUncommonIdentifiers.randomElement() {
			planned.append(PlannedCard(card, isFoil: true))
		}
	case 454...973:
		if let card = futureSightRareMythicIdentifiers.randomElement() {
			planned.append(PlannedCard(card))
		}
	case 974...997:
		if let card = futureSightRareMythicIdentifiers.randomElement() {
			planned.append(PlannedCard(card, isFoil: true))
		}
	default:
		if let acorn = acornIdentifiers.randomElement() {
			planned.append(PlannedCard(acorn, isFoil: true))
		}
	}

	// 1 playtest card.
	if let playtest = playtestIdentifiers.randomElement() {
		planned.append(PlannedCard(playtest))
	}

	return planned
}

/// Generates the requested number of Mystery Booster: Commander Edition packs.
///
/// Each pack's cards are chosen first, then only the selected cards are fetched from Scryfall
/// (deduplicated across all packs in the request and batched into as few requests as possible).
///
/// The reprint slots prefer their The List (`plst`) printing, whose collector number is hardcoded.
/// The primary (List) printings are fetched first, and only the fallbacks (original printings) for
/// any the List doesn't have are fetched in a second pass.
func generateMysteryBoosterCommanderPacks(count: Int) async throws -> [CardCollection] {
	guard count > 0 else { return [] }

	let plans: [[PlannedCard]] = (0..<count).map { _ in planMysteryBoosterCommanderPack() }

	// Fetch every card's primary printing (the List printing for reprint slots, the card itself
	// for the others).
	let primaryIdentifiers = Array(Set(plans.flatMap { $0.map(\.primary) }))
	let primaryCards = await fetchCards(primaryIdentifiers)

	// Fetch fallbacks only for cards whose primary printing wasn't found.
	let neededFallbacks = Set(plans.flatMap { plan in
		plan.compactMap { planned in
			primaryCards[planned.primary] == nil ? planned.fallback : nil
		}
	})
	let fallbackCards = neededFallbacks.isEmpty ? [] : await fetchCards(Array(neededFallbacks))

	// Assemble each pack, preferring the primary printing and preserving slot order and foil status.
	return plans.map { plan in
		var pack = CardCollection()
		for planned in plan {
			let card = primaryCards[planned.primary] ?? planned.fallback.flatMap { fallbackCards[$0] }
			if let card {
				pack.append(card, isFoil: planned.isFoil)
			}
		}
		return pack
	}
}
